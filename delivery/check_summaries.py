"""Project execution evidence to bounded model-facing facts, never raw test I/O.

The owner can inspect full reports through authenticated APIs. Model requests
receive only check status and application-authored explanations. Container
stdout/stderr can echo private inputs and must not enter later model requests.
"""


def model_validation(report):
    if not isinstance(report, dict):
        return {}
    checks = report.get('checks', [])
    projected = []
    for check in checks if isinstance(checks, list) else []:
        if not isinstance(check, dict):
            continue
        row = {key: check[key] for key in ('path', 'tool', 'check', 'status', 'detail', 'reason_code')
               if isinstance(check.get(key), str)}
        # Details for this tool are generated by the application. Do not copy
        # nested execution cases, hashes, stdout, stderr, or the signed receipt.
        if check.get('tool') == 'python_stdio':
            row['detail'] = {'passed': '已保存的用户输入输出用例通过；只覆盖这些用例。',
                             'failed': '用户输入输出验收未通过；请根据任务要求修正程序。',
                             'not_run': '用户输入输出验收尚未执行，不得宣称通过。'}.get(
                                 check.get('status'), '没有可信的输入输出验收结论。')
            if type(check.get('requested_cases')) is int:
                row['requested_cases'] = check['requested_cases']
            cases = check.get('cases', [])
            if isinstance(cases, list):
                row['case_statuses'] = [case.get('status', 'not_run') for case in cases
                                        if isinstance(case, dict)]
        projected.append(row)
    return {'passed': report.get('passed') is True, 'checks': projected,
            'scope': report.get('scope', '') if isinstance(report.get('scope', ''), str) else ''}
